/**
 * ПРЕОБРАЗОВАТЕЛЬ ИЗ ИНФИКСНОЙ ЗАПИСИ В ПОСТФИКСНУЮ
 * - Работает только с однозначными цифрами (0-9)
 * - Алгоритм "сортировочной станции" Э. Дейкстры
 */

#include <ctype.h> // Для функции isdigit()
#include <stdio.h>
#include <string.h> // Для работы со строками

/*
 * Константы программы
 */
#define MAX 100 // Максимальный размер стека и входной строки

/*
 * Глобальные переменные для стека
 */
char stack[MAX]; // Массив, представляющий стек
int top = -1; // Индекс вершины стека (-1 означает пустой стек)

/**
 * ФУНКЦИИ ДЛЯ РАБОТЫ СО СТЕКОМ
 */

/**
 * Добавление элемента в стек (операция PUSH)
 * @param c: символ для добавления в стек
 */
void push(char c)
{
    // Увеличиваем top и сохраняем элемент на вершину стека
    stack[++top] = c;
}

/**
 * Извлечение элемента из стека (операция POP)
 * @return: символ с вершины стека
 */
char pop()
{
    // Возвращаем элемент с вершины и уменьшаем top
    return stack[top--];
}

/**
 * Просмотр верхнего элемента без извлечения (операция PEEK)
 * @return: символ с вершины стека без удаления
 */
char peek()
{
    return stack[top]; // Просто возвращаем верхний элемент
}

/**
 * Проверка стека на пустоту
 * @return: 1 если стек пуст, 0 если нет
 */
int isStackEmpty()
{
    return top == -1; // top = -1 означает пустой стек
}

/**
 * ОПРЕДЕЛЕНИЕ ПРИОРИТЕТА ОПЕРАТОРОВ
 */

/**
 * Определение приоритета математического оператора
 * @param op: символ оператора (+, -, *, /)
 * @return: числовой приоритет (чем больше число, тем выше приоритет)
 */
int getPriority(char op)
{
    switch (op) {
    case '+':
    case '-':
        return 1; // Низкий приоритет для сложения и вычитания

    case '*':
    case '/':
        return 2; // Высокий приоритет для умножения и деления

    default:
        return 0; // Для всех остальных символов (скобки, числа)
    }
}

/**
 * Проверка, является ли символ математическим оператором
 * @param c: проверяемый символ
 * @return: 1 если оператор, 0 если нет
 */
int isOperator(char c)
{
    return c == '+' || c == '-' || c == '*' || c == '/';
}

/**
 * ОСНОВНАЯ ФУНКЦИЯ ПРЕОБРАЗОВАНИЯ
 */

/**
 * Преобразует инфиксное выражение в постфиксное
 *
 * АЛГОРИТМ "СОРТИРОВОЧНОЙ СТАНЦИИ":
 * 1. Инициализируем пустой стек и пустую выходную строку
 * 2. Для каждого символа во входной строке:
 *    а) Если символ - цифра: добавляем в выход
 *    б) Если символ - '(': помещаем в стек
 *    в) Если символ - ')': выталкиваем операторы из стека до '('
 *    г) Если символ - оператор:
 *       - Пока на вершине стека оператор с ≥ приоритетом, выталкиваем его в выход
 *       - Помещаем текущий оператор в стек
 * 3. После обработки всех символов выталкиваем оставшиеся операторы из стека
 *
 * @param infix: строка с инфиксным выражением (только однозначные цифры)
 * @return: строка с постфиксным выражением (результат преобразования)
 */
void infixToPostfix(char* infix, char* postfix)
{
    int j = 0; // Индекс для записи в выходную строку postfix
    top = -1; // Сбрасываем стек перед началом обработки нового выражения

    // Проходим по каждому символу входной строки
    for (int i = 0; infix[i] != '\0'; i++) {
        char current = infix[i]; // Текущий обрабатываемый символ

        // Пропускаем пробелы
        if (current == ' ')
            continue;

        // СЛУЧАЙ 1: Символ - цифра (0-9)
        if (isdigit(current)) {
            // Цифры сразу идут в выходную строку
            postfix[j++] = current;
            postfix[j++] = ' '; // Добавляем пробел как разделитель
        }

        // СЛУЧАЙ 2: Открывающая скобка '('
        else if (current == '(') {
            push(current); // Открывающие скобки всегда помещаются в стек
        }

        // СЛУЧАЙ 3: Закрывающая скобка ')'
        else if (current == ')') {
            // Выталкиваем все операторы из стека до открывающей скобки
            while (!isStackEmpty() && peek() != '(') {
                postfix[j++] = pop(); // Добавляем оператор в выход
                postfix[j++] = ' '; // Добавляем пробел после оператора
            }

            // Удаляем саму открывающую скобку из стека
            pop();
        }

        // СЛУЧАЙ 4: Математический оператор (+, -, *, /)
        else if (isOperator(current)) {
            // Выталкиваем из стека все операторы с высшим или равным приоритетом
            while (!isStackEmpty() && isOperator(peek()) && getPriority(peek()) >= getPriority(current)) {
                postfix[j++] = pop(); // Добавляем оператор в выход
                postfix[j++] = ' '; // Добавляем пробел после оператора
            }

            // Помещаем текущий оператор в стек
            push(current);
        }
    }

    // ЗАВЕРШАЮЩИЙ ЭТАП: выталкиваем все оставшиеся операторы из стека
    while (!isStackEmpty()) {
        postfix[j++] = pop(); // Добавляем оставшиеся операторы в выход
        postfix[j++] = ' '; // Добавляем пробел после оператора
    }

    // Завершаем строку нулевым символом
    postfix[j] = '\0';
}

/**
 * ГЛАВНАЯ ФУНКЦИЯ ПРОГРАММЫ
 * Реализует интерактивный режим работы с пользователем
 */
int main()
{
    char infix[MAX]; // Буфер для вводимого инфиксного выражения
    char postfix[MAX]; // Буфер для результата (постфиксное выражение)

    printf("ПРЕОБРАЗОВАТЕЛЬ ИНФИКСНОЙ ЗАПИСИ В ПОСТФИКСНУЮ\n");
    printf("Поддерживаются: цифры 0-9, операторы + - * /, скобки ( )\n");
    printf("Для выхода введите 'exit'\n\n");

    // Бесконечный цикл для интерактивного режима
    while (1) {
        printf("Введите выражение: ");

        // Чтение ввода пользователя
        if (fgets(infix, MAX, stdin) == NULL) {
            break; // В случае ошибки ввода выходим из цикла
        }

        // Удаление символа новой строки из ввода
        infix[strcspn(infix, "\n")] = 0;

        // Проверка команды выхода
        if (strcmp(infix, "exit") == 0) {
            break; // Выход из цикла при вводе "exit"
        }

        // Пропускаем пустой ввод
        if (strlen(infix) == 0) {
            continue;
        }

        // Выполняем преобразование выражения
        infixToPostfix(infix, postfix);

        // Выводим результат преобразования
        printf("Инфиксная запись:  %s\n", infix);
        printf("Постфиксная запись: %s\n\n", postfix);
    }

    printf("Выход из программы.\n");
    return 0;
}
